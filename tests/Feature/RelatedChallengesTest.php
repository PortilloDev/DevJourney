<?php

declare(strict_types=1);

namespace Tests\Feature;

use App\Filament\Resources\PostResource\Pages\EditPost;
use App\Filament\Resources\PostResource\RelationManagers\ChallengesRelationManager;
use App\Models\Challenge;
use App\Models\Post;
use App\Models\Tag;
use App\Models\User;
use App\Services\Embedding\EmbeddingService;
use App\Services\Llm\LlmClient;
use App\Services\Rag\RagService;
use App\Services\Vector\InMemoryVectorStore;
use App\Services\Vector\VectorStore;
use Illuminate\Foundation\Testing\RefreshDatabase;
use Illuminate\Support\Facades\Cache;
use Livewire\Livewire;
use Tests\TestCase;

class RelatedChallengesTest extends TestCase
{
    use RefreshDatabase;

    private InMemoryVectorStore $store;

    private RelatedEmbedding $embedding;

    private RelatedLlm $llm;

    protected function setUp(): void
    {
        parent::setUp();

        Cache::flush();

        config([
            'rag.qdrant.enabled' => false,
            'rag.retrieval.min_similarity' => 0.30,
            'rag.retrieval.related_min_similarity' => 0.20,
            'rag.post_chat.related_threshold' => 0.5,
            'rag.post_chat.unrelated_threshold' => 0.15,
            'rag.indexing.source_types' => ['post', 'document'],
        ]);

        $this->store = new InMemoryVectorStore;
        $this->embedding = new RelatedEmbedding;
        $this->llm = new RelatedLlm;

        $this->app->instance(VectorStore::class, $this->store);
        $this->app->instance(EmbeddingService::class, $this->embedding);
        $this->app->instance(LlmClient::class, $this->llm);
    }

    // R1-E1: the pivot persists the link and is queryable from both sides, and
    // the relation manager attaches it from the panel.
    public function test_a_challenge_is_linked_to_a_post_both_ways_and_from_the_panel(): void
    {
        $post = Post::factory()->create();
        $challenge = Challenge::factory()->create();

        $email = 'admin@devjourney.test';
        config(['app.filament_admin_email' => $email]);
        $admin = User::factory()->create(['email' => $email]);

        $this->actingAs($admin);

        Livewire::test(ChallengesRelationManager::class, [
            'ownerRecord' => $post,
            'pageClass' => EditPost::class,
        ])
            ->callTableAction('attach', null, ['recordId' => $challenge->getKey()])
            ->assertHasNoTableActionErrors();

        $this->assertSame(
            [$challenge->getKey()],
            $post->fresh()->challenges->pluck('id')->all(),
        );
        $this->assertSame(
            [$post->getKey()],
            $challenge->fresh()->posts->pluck('id')->all(),
        );
    }

    // R2-E1: the post page lists published linked challenges with title and
    // link, and hides draft ones.
    public function test_the_post_page_lists_published_linked_challenges_with_links(): void
    {
        $post = Post::factory()->create();
        $published = Challenge::factory()->create(['title' => 'PUBLISHED_CHALLENGE_MARKER']);
        $draft = Challenge::factory()->draft()->create(['title' => 'DRAFT_CHALLENGE_MARKER']);

        $post->challenges()->attach([$published->getKey(), $draft->getKey()]);

        $response = $this->get(route('posts.show', $post));

        $response->assertOk();
        $response->assertSee('PUBLISHED_CHALLENGE_MARKER');
        $response->assertSee(route('challenges.show', $published), false);
        $response->assertDontSee('DRAFT_CHALLENGE_MARKER');
    }

    // R3-E1: a non-rejected answer carries the linked challenges, with URLs
    // generated by the application.
    public function test_a_non_rejected_answer_carries_the_linked_challenges(): void
    {
        [$post, $challenge] = $this->answeredPost();

        $result = app(RagService::class)->askForPost(
            $post,
            'How does hexagonal architecture isolate the domain?',
            useCache: false,
        );

        $this->assertFalse($result['refused']);
        $this->assertSame([
            [
                'title' => 'RELATED_CHALLENGE_MARKER',
                'url' => route('challenges.show', $challenge),
            ],
        ], $result['related']);
    }

    // R3-E2: a rejected question carries no challenges at all.
    public function test_a_rejected_answer_carries_no_challenges(): void
    {
        [$post] = $this->answeredPost();

        $result = app(RagService::class)->askForPost($post, 'kubernetes autoscaling', useCache: false);

        $this->assertTrue($result['refused']);
        $this->assertSame([], $result['related']);
    }

    // R4-E1 (negative): a challenge named only in the model's prose never shows
    // up; the list comes exclusively from the pivot.
    public function test_challenges_come_from_the_database_not_from_the_model_text(): void
    {
        [$post] = $this->answeredPost();

        $this->llm->content = 'Try the INVENTED_CHALLENGE at https://evil.example/fake';

        $result = app(RagService::class)->askForPost(
            $post,
            'How does hexagonal architecture isolate the domain?',
            useCache: false,
        );

        $this->assertStringContainsString('INVENTED_CHALLENGE', (string) $result['answer']);

        $titles = array_column($result['related'], 'title');

        $this->assertSame(['RELATED_CHALLENGE_MARKER'], $titles);
        $this->assertNotContains('INVENTED_CHALLENGE', $titles);
    }

    // R3-E1: the JSON contract exposes the related field.
    public function test_the_json_response_exposes_the_related_challenges(): void
    {
        [$post, $challenge] = $this->answeredPost();

        $this->postJson('/api/chat', [
            'question' => 'How does hexagonal architecture isolate the domain?',
            'post' => $post->slug,
        ])->assertOk()
            ->assertJsonPath('related.0.title', 'RELATED_CHALLENGE_MARKER')
            ->assertJsonPath('related.0.url', route('challenges.show', $challenge));
    }

    // R3-E1 + R3-E2: the final SSE event exposes the related field, empty on a
    // rejected answer.
    public function test_the_final_sse_event_exposes_the_related_challenges(): void
    {
        [$post, $challenge] = $this->answeredPost();

        $content = $this->postJson('/api/chat', [
            'question' => 'How does hexagonal architecture isolate the domain?',
            'post' => $post->slug,
            'stream' => true,
        ])->assertOk()->streamedContent();

        $done = $this->doneEvent($content);

        $this->assertNotNull($done);
        $this->assertSame([
            [
                'title' => 'RELATED_CHALLENGE_MARKER',
                'url' => route('challenges.show', $challenge),
            ],
        ], $done['related']);

        $refused = $this->postJson('/api/chat', [
            'question' => 'kubernetes autoscaling',
            'post' => $post->slug,
            'stream' => true,
        ])->assertOk()->streamedContent();

        $this->assertSame([], $this->doneEvent($refused)['related'] ?? []);
    }

    // R5-E1: published challenges sharing tags with the post are proposed first,
    // without excluding the rest.
    public function test_candidates_put_challenges_sharing_tags_with_the_post_first(): void
    {
        $post = Post::factory()->create();
        $tag = Tag::create(['name' => 'DDD']);
        $post->tags()->attach($tag->getKey());

        $shared = Challenge::factory()->create(['title' => 'SHARED_TAG_CHALLENGE']);
        $shared->tags()->attach($tag->getKey());
        $other = Challenge::factory()->create(['title' => 'OTHER_CHALLENGE']);

        $ids = Challenge::query()->suggestedForPost($post)->pluck('id')->all();

        $this->assertSame($shared->getKey(), $ids[0]);
        $this->assertContains($other->getKey(), $ids);
    }

    // R6-E1 (negative): a published challenge whose type is disabled is never
    // embedded and writes no point.
    public function test_challenges_are_not_indexed_when_the_type_is_disabled(): void
    {
        config([
            'rag.api_key' => 'test',
            'rag.embeddings.api_key' => 'test',
            'rag.indexing.source_types' => ['post', 'document'],
        ]);

        $this->embedding->calls = 0;

        $challenge = Challenge::factory()->create();

        $this->assertSame(0, $this->embedding->calls);
        $this->assertSame([], $this->challengePoints($challenge));
    }

    // R6: the cleanup command removes already-indexed challenge points.
    public function test_the_cleanup_command_removes_challenge_vectors(): void
    {
        $challenge = Challenge::factory()->create();
        $draft = Challenge::factory()->draft()->create();

        $this->store->upsert([
            [
                'id' => 'challenge-point',
                'vector' => [1.0, 0.0, 0.0],
                'payload' => [
                    'source_type' => 'challenge',
                    'source_id' => 'challenge:'.$challenge->getKey(),
                    'title' => 'Old challenge',
                    'text' => 'Unreachable content.',
                ],
            ],
            [
                'id' => 'draft-challenge-point',
                'vector' => [1.0, 0.0, 0.0],
                'payload' => [
                    'source_type' => 'challenge',
                    'source_id' => 'challenge:'.$draft->getKey(),
                    'title' => 'Draft challenge',
                    'text' => 'Unreachable content.',
                ],
            ],
        ]);

        $this->artisan('rag:prune-challenge-vectors')->assertSuccessful();

        $this->assertSame([], $this->challengePoints($challenge));
        $this->assertSame([], $this->challengePoints($draft));
    }

    /**
     * @return array<string, mixed>|null
     */
    private function doneEvent(string $content): ?array
    {
        $done = null;

        foreach (explode("\n", $content) as $line) {
            if (! str_starts_with($line, 'data: ')) {
                continue;
            }

            $payload = json_decode(substr($line, 6), true);

            if (is_array($payload) && ($payload['done'] ?? false) === true) {
                $done = $payload;
            }
        }

        return $done;
    }

    /**
     * @return array{0: Post, 1: Challenge}
     */
    private function answeredPost(): array
    {
        $post = Post::factory()->create([
            'title' => 'Hexagonal architecture',
            'body_md' => '## Intro'.PHP_EOL.'Hexagonal architecture isolates the domain from frameworks.',
        ]);

        $challenge = Challenge::factory()->create(['title' => 'RELATED_CHALLENGE_MARKER']);
        $post->challenges()->attach($challenge->getKey());

        $this->store->upsert([[
            'id' => 'post-point',
            'vector' => [1.0, 0.0, 0.0],
            'payload' => [
                'source_type' => 'post',
                'source_id' => 'post:'.$post->getKey(),
                'title' => $post->title,
                'text' => 'Hexagonal architecture isolates the domain.',
            ],
        ]]);

        return [$post, $challenge];
    }

    /**
     * @return list<array<string, mixed>>
     */
    private function challengePoints(Challenge $challenge): array
    {
        return $this->store->search(
            [1.0, 0.0, 0.0],
            10,
            ['must' => [['key' => 'source_id', 'value' => 'challenge:'.$challenge->getKey()]]],
        );
    }
}

final class RelatedEmbedding implements EmbeddingService
{
    public int $calls = 0;

    public function embed(string $text): array
    {
        $this->calls++;

        return [1.0, 0.0, 0.0];
    }

    public function embedMany(array $texts): array
    {
        return array_map(fn (): array => [1.0, 0.0, 0.0], $texts);
    }

    public function dimensions(): int
    {
        return 3;
    }
}

final class RelatedLlm implements LlmClient
{
    public string $content = 'Related answer.';

    public function complete(array $messages, ?int $maxTokens = null, ?string $model = null, ?float $temperature = null): array
    {
        return [
            'content' => $this->content,
            'tokens_in' => 10,
            'tokens_out' => 4,
            'model' => 'related-llm',
            'finish_reason' => 'stop',
        ];
    }

    public function stream(array $messages, callable $onDelta, ?int $maxTokens = null, ?string $model = null): array
    {
        ($onDelta)($this->content);

        return [
            'content' => $this->content,
            'tokens_in' => 10,
            'tokens_out' => 4,
            'model' => 'related-llm',
            'finish_reason' => 'stop',
        ];
    }
}
